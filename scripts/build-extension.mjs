/**
 * Builds the two files the extension needs from the website's own code.
 *
 *   node scripts/build-extension.mjs
 *
 *   extension/src/resume.js            src/extension/resume-reader.ts, bundled
 *   extension/vendor/pdf.min.mjs       pdf.js, copied from node_modules
 *   extension/vendor/pdf.worker.min.mjs
 *
 * The outputs are COMMITTED, like any vendored file: someone loading the
 * extension unpacked should not need npm first. tests/extension-build.test.ts
 * fails if the committed bundle is stale against its sources.
 */
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXT = path.join(ROOT, 'extension');

export async function bundleResumeReader() {
  const out = await build({
    entryPoints: [path.join(ROOT, 'src/extension/resume-reader.ts')],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'chrome120',
    write: false,
    legalComments: 'none',
    charset: 'utf8',
  });
  const header = '// GENERATED by scripts/build-extension.mjs from src/extension/resume-reader.ts — do not edit.\n';
  return header + out.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(EXT, 'src/resume.js'), await bundleResumeReader());
  mkdirSync(path.join(EXT, 'vendor'), { recursive: true });
  for (const f of ['pdf.min.mjs', 'pdf.worker.min.mjs']) {
    copyFileSync(path.join(ROOT, 'node_modules/pdfjs-dist/build', f), path.join(EXT, 'vendor', f));
  }
  const version = JSON.parse(readFileSync(path.join(ROOT, 'node_modules/pdfjs-dist/package.json'), 'utf8')).version;
  writeFileSync(path.join(EXT, 'vendor/README.md'), `pdf.js ${version} (Apache-2.0), copied from node_modules/pdfjs-dist/build by scripts/build-extension.mjs.\nUsed only on the options page, to read the text of a résumé you choose. Nothing is sent anywhere.\n`);
  console.log('built extension/src/resume.js and extension/vendor/ (pdf.js', version + ')');
}
